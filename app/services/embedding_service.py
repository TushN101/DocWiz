class EmbeddingService:
    """Facade used by the rest of the app — same interface as before.

    embed_documents(texts) → (n, dim) float32, L2-normalized
    embed_query(question)  → (1, dim) float32, L2-normalized
    """

    def __init__(self, provider, backend, model, embedding_id, cache_path=None, cache_enabled=True):
        self.provider = provider
        self.model = model
        self.backend = backend
        self.embedding_id = embedding_id
        self._cache_path = Path(cache_path) if cache_path else None
        self._cache_enabled = cache_enabled
        self._cache = {}
        self._cache_loaded = False
        self._cache_lock = threading.Lock()

    # ---------------------------------------------------------------- state
    @property
    def loaded(self) -> bool:
        """True once the provider is ready to embed (key present / model built)."""
        return self.backend.ready

    # ---------------------------------------------------------------- public
    def embed_documents(self, texts):
        texts = list(texts)
        if not texts:
            return np.zeros((0, 0), dtype=np.float32)
        self._guard_ready()
        return self._embed_with_cache(texts, task_type="document")

    def embed_query(self, question: str):
        self._guard_ready()
        return self._embed_with_cache([question], task_type="query")

    def _guard_ready(self):
        """Fail fast with an actionable message when the provider needs a key."""
        if self.backend.ready:
            return
        defaults = PROVIDER_DEFAULTS.get(self.provider, {})
        hint = defaults.get("key_hint") or "set EMBEDDING_API_KEY in your .env file"
        raise AppError(
            "embedding_api_key_missing",
            f"No API key configured for the '{self.provider}' embedding provider — {hint}.",
            503,
        )

    # ---------------------------------------------------------------- internals
    def _embed_with_cache(self, texts, task_type):
        cache_key = self._cache_key_for(task_type)
        results = [None] * len(texts)
        missing_idx, missing_texts = [], []

        if self._cache_enabled:
            with self._cache_lock:
                self._ensure_cache_loaded()
                for i, text in enumerate(texts):
                    key = cache_key(text)
                    cached = self._cache.get(key)
                    if cached is not None:
                        results[i] = cached
                    else:
                        missing_idx.append(i)
                        missing_texts.append(text)
        else:
            missing_idx, missing_texts = list(range(len(texts))), texts

        if missing_texts:
            task = self._task_constant(task_type)
            vectors = self.backend.embed(missing_texts, task_type=task)
            for row, i in enumerate(missing_idx):
                results[i] = vectors[row].astype(np.float32)
            if self._cache_enabled:
                with self._cache_lock:
                    for row, i in enumerate(missing_idx):
                        self._cache[cache_key(texts[i])] = results[i].copy()
                    self._persist_cache()

        matrix = np.vstack(results)
        return _l2_normalize(matrix.astype(np.float32))

    def _task_constant(self, task_type):
        if self.provider != "gemini":
            return None
        return "RETRIEVAL_DOCUMENT" if task_type == "document" else "RETRIEVAL_QUERY"

    def _cache_key_for(self, task_type):
        prefix = f"{self.embedding_id}|{task_type}|"

        def key(text):
            return hashlib.sha256((prefix + text).encode("utf-8")).hexdigest()

        return key

    def _ensure_cache_loaded(self):
        if self._cache_loaded or self._cache_path is None:
            return
        if not self._cache_path.exists():
            self._cache_loaded = True
            return
        try:
            with np.load(self._cache_path) as archive:
                for name in archive.files:
                    self._cache[name] = archive[name].astype(np.float32)
            logger.info("Embedding cache restored: %s vector(s).", len(self._cache))
        except (OSError, ValueError, KeyError):
            logger.warning("Embedding cache unreadable — starting a fresh cache.")
        self._cache_loaded = True

    def _persist_cache(self):
        if self._cache_path is None or not self._cache:
            return
        try:
            self._cache_path.parent.mkdir(parents=True, exist_ok=True)
            tmp = self._cache_path.with_suffix(".tmp.npz")
            np.savez(tmp, **self._cache)
            tmp.replace(self._cache_path)  # atomic-ish swap; no partial reads
        except OSError:
            logger.warning("Could not persist the embedding cache — continuing without it.", exc_info=True)


