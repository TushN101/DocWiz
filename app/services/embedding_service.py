"""Pluggable text-embedding layer for DocWiz.

Why providers? Running Sentence-Transformers locally pulls in PyTorch —
and on many Linux wheels the whole CUDA/NVIDIA stack (multi-GB). That is
a poor fit for a small VM. Embeddings are therefore generated by a
configurable provider (default: Google's Gemini API, free tier) and the
rest of the pipeline is untouched: vectors are still L2-normalized
float32 rows compared by cosine similarity in the local NumPy store.

Providers (EMBEDDING_PROVIDER env var):
  gemini              Google AI Studio — generous free tier (default).
                      Model: gemini-embedding-001 (text, task types,
                      Matryoshka output_dimensionality).
  openai-compatible   Any OpenAI-style POST {base}/embeddings endpoint —
                      Jina, Mistral, OpenAI, Together, local Ollama, …
  groq                Groq's embeddings endpoint (nomic-embed-text-v1_5).
                      Optional convenience preset; shares GROQ_API_KEY.
  hashing             Built-in offline lexical encoder — zero network,
                      zero dependencies (test suite / emergency fallback;
                      keyword-level quality only, not semantic).
  local               Sentence-Transformers on CPU (legacy behaviour;
                      optional install — see requirements-local.txt).

Every provider returns L2-normalized float32 vectors, so cosine
similarity stays a plain dot product in the vector store.

Quota friendliness (free tiers): requests are batched, transient 429/5xx
responses are retried honouring Retry-After, and a small on-disk cache
(data/embedding_cache.npz) memoizes vectors per (provider, model, text)
so re-indexing the same content never pays twice.
"""
import hashlib
import json
import logging
import re
import threading
import time
from pathlib import Path

import numpy as np
import requests

from app.utils.errors import AppError

logger = logging.getLogger("docwiz.embeddings")

# --------------------------------------------------------------------------
# Shared helpers
# --------------------------------------------------------------------------


def _l2_normalize(matrix: np.ndarray) -> np.ndarray:
    norms = np.linalg.norm(matrix, axis=1, keepdims=True)
    norms[norms == 0] = 1.0
    return matrix / norms


def _error_body_message(body) -> str:
    """Best-effort extraction of an API error message from a JSON body."""
    if isinstance(body, dict):
        err = body.get("error")
        if isinstance(err, dict):
            return str(err.get("message") or err.get("status") or body)
        if isinstance(err, str):
            return err
        return str(body)
    return str(body)


def _post_with_retries(url, payload, headers, timeout, retries):
    """POST JSON with retry on 429/5xx/network errors, honouring Retry-After.

    Returns the parsed JSON body. Raises AppError with a precise code on
    permanent failures so the UI can show an actionable message.
    """
    attempts = max(1, retries + 1)
    last_status, last_body = None, None
    for attempt in range(attempts):
        try:
            response = requests.post(url, json=payload, headers=headers, timeout=timeout)
        except requests.exceptions.Timeout:
            if attempt + 1 < attempts:
                time.sleep(1.5)
                continue
            raise AppError(
                "embedding_timeout",
                "The embedding service did not respond in time. Try again shortly.",
                504,
            )
        except requests.exceptions.RequestException as exc:
            if attempt + 1 < attempts:
                time.sleep(1.5)
                continue
            raise AppError(
                "embedding_unreachable",
                f"Could not reach the embedding service: {exc.__class__.__name__}. "
                "Check your internet connection and try again.",
                502,
            )

        last_status, last_body = response.status_code, _safe_json(response)

        if response.status_code < 400:
            return last_body

        retryable = response.status_code == 429 or response.status_code >= 500
        if retryable and attempt + 1 < attempts:
            delay = _retry_after_seconds(response) or min(1.5 * (attempt + 1), 8.0)
            logger.warning(
                "Embedding API returned %s — retrying in %.1fs (attempt %s/%s)",
                response.status_code, delay, attempt + 1, attempts,
            )
            time.sleep(delay)
            continue
        break

    _raise_api_error(last_status, last_body, response)


def _raise_api_error(status, body, response):
    message = _error_body_message(body)
    if status == 401 or status == 403:
        raise AppError(
            "embedding_auth_failed",
            "The embedding API rejected the configured key. Check "
            "EMBEDDING_API_KEY in your .env file. (" + message[:200] + ")",
            502,
        )
    if status == 404:
        raise AppError(
            "embedding_model_unavailable",
            "The configured embedding model was not found on the provider. "
            "Check EMBEDDING_MODEL. (" + message[:200] + ")",
            502,
        )
    if status == 429:
        retry = _retry_after_seconds(response) if response is not None else None
        hint = f" Try again in ~{int(retry)}s." if retry else ""
        raise AppError(
            "embedding_rate_limited",
            "Embedding rate limit reached on the provider's free tier." + hint,
            429,
        )
    if status == 400:
        raise AppError(
            "embedding_bad_request",
            "The embedding API rejected the request. (" + message[:200] + ")",
            502,
        )
    raise AppError(
        "embedding_api_error",
        f"The embedding service returned HTTP {status}. (" + message[:200] + ")",
        502,
    )


def _safe_json(response):
    try:
        return response.json()
    except ValueError:
        return {"error": {"message": (response.text or "")[:300]}}


def _retry_after_seconds(response) -> float | None:
    try:
        value = response.headers.get("Retry-After")
        return float(value) if value else None
    except (TypeError, ValueError, AttributeError):
        return None


# --------------------------------------------------------------------------
# Backends (each knows how to embed a list of texts in one or more requests)
# --------------------------------------------------------------------------


class _GeminiBackend:
    """Google Gemini API embeddings (generativelanguage.googleapis.com).

    Uses :batchEmbedContents with one request per text. Verified against
    the official docs (ai.google.dev/gemini-api/docs/embeddings):
      * header  x-goog-api-key
      * body    {"requests": [{"model": "models/<m>", "content":
                 {"parts": [{"text": ...}]}, "task_type": ...,
                 "output_dimensionality": n}, ...]}
      * response {"embeddings": [{"values": [...], ...}, ...]}
    """

    MAX_PER_REQUEST = 64  # stays under the provider's batch cap

    def __init__(self, api_key, model, api_base, output_dims, task_document, task_query, timeout, retries):
        self.api_key = api_key
        self.model = model
        self.api_base = (api_base or "https://generativelanguage.googleapis.com/v1beta").rstrip("/")
        self.output_dims = output_dims
        self.task_document = task_document
        self.task_query = task_query
        self.timeout = timeout
        self.retries = retries

    @property
    def ready(self) -> bool:
        return bool(self.api_key)

    def _request_entry(self, text, task_type):
        entry = {"model": f"models/{self.model}", "content": {"parts": [{"text": text}]}}
        if task_type:
            entry["task_type"] = task_type
        if self.output_dims:
            entry["output_dimensionality"] = self.output_dims
        return entry

    def embed(self, texts, task_type=None):
        url = f"{self.api_base}/models/{self.model}:batchEmbedContents"
        headers = {"x-goog-api-key": self.api_key, "Content-Type": "application/json"}
        embeddings = []
        for start in range(0, len(texts), self.MAX_PER_REQUEST):
            batch = texts[start : start + self.MAX_PER_REQUEST]
            payload = {"requests": [self._request_entry(t, task_type) for t in batch]}
            body = _post_with_retries(url, payload, headers, self.timeout, self.retries)
            rows = body.get("embeddings") if isinstance(body, dict) else None
            if not rows or len(rows) != len(batch):
                raise AppError(
                    "embedding_api_error",
                    "The embedding API returned an unexpected response shape.",
                    502,
                )
            for row in rows:
                values = row.get("values") if isinstance(row, dict) else None
                if not values:
                    raise AppError(
                        "embedding_api_error",
                        "The embedding API returned an empty embedding.",
                        502,
                    )
                embeddings.append(values)
        matrix = np.asarray(embeddings, dtype=np.float32)
        return _l2_normalize(matrix)


class _OpenAICompatBackend:
    """Any OpenAI-style embeddings endpoint: POST {base}/embeddings.

    Works with Jina (api.jina.ai/v1), Mistral, OpenAI, Together,
    Fireworks, SiliconFlow, local Ollama (http://localhost:11434/v1), …
    """

    MAX_PER_REQUEST = 128

    def __init__(self, api_key, model, api_base, timeout, retries):
        self.api_key = api_key
        self.model = model
        self.api_base = api_base.rstrip("/")
        self.timeout = timeout
        self.retries = retries

    @property
    def ready(self) -> bool:
        return True  # some compatible endpoints (Ollama) need no key

    def embed(self, texts, task_type=None):
        url = f"{self.api_base}/embeddings"
        headers = {"Content-Type": "application/json"}
        if self.api_key:
            headers["Authorization"] = f"Bearer {self.api_key}"
        embeddings = []
        for start in range(0, len(texts), self.MAX_PER_REQUEST):
            batch = texts[start : start + self.MAX_PER_REQUEST]
            payload = {"model": self.model, "input": batch}
            body = _post_with_retries(url, payload, headers, self.timeout, self.retries)
            rows = body.get("data") if isinstance(body, dict) else None
            if not rows or len(rows) != len(batch):
                raise AppError(
                    "embedding_api_error",
                    "The embedding API returned an unexpected response shape.",
                    502,
                )
            rows = sorted(rows, key=lambda r: r.get("index", 0))
            for row in rows:
                values = row.get("embedding")
                if not values:
                    raise AppError(
                        "embedding_api_error",
                        "The embedding API returned an empty embedding.",
                        502,
                    )
                embeddings.append(values)
        matrix = np.asarray(embeddings, dtype=np.float32)
        return _l2_normalize(matrix)


class _HashingBackend:
    """Deterministic offline encoder (no network, no dependencies).

    Signed random projection over token hashes: each word is hashed to a
    few buckets with +/− signs; vectors are normalized. Captures lexical
    overlap (shared terms → higher cosine) but NOT paraphrase semantics.
    Used by the test suite and as a zero-dependency fallback.
    """

    def __init__(self, dims=256):
        self.dims = dims

    @property
    def ready(self) -> bool:
        return True

    def _token_vector(self, text):
        vector = np.zeros(self.dims, dtype=np.float32)
        for token in re.findall(r"[a-z0-9]{2,}", (text or "").lower()):
            digest = hashlib.sha1(token.encode("utf-8")).digest()
            bucket = int.from_bytes(digest[:2], "big") % self.dims
            sign = 1.0 if digest[2] % 2 == 0 else -1.0
            vector[bucket] += sign
            # a second, co-occurrence bucket widens the signal slightly
            bucket2 = int.from_bytes(digest[3:5], "big") % self.dims
            vector[bucket2] += sign * 0.5
        return vector

    def embed(self, texts, task_type=None):
        matrix = np.vstack([self._token_vector(t) for t in texts])
        return _l2_normalize(matrix)


class _LocalSentenceTransformerBackend:
    """Legacy local embeddings (Sentence-Transformers on CPU).

    Kept for offline setups. Optional dependency: installing
    requirements-local.txt pulls PyTorch (large) — exactly what the
    provider switch is meant to avoid, so nothing imports this module
    unless EMBEDDING_PROVIDER=local.
    """

    def __init__(self, model_name, batch_size):
        self.model_name = model_name
        self.batch_size = batch_size
        self._model = None
        self._lock = threading.Lock()

    @property
    def ready(self) -> bool:
        return self._model is not None

    def _ensure_model(self):
        if self._model is not None:
            return self._model
        with self._lock:
            if self._model is not None:
                return self._model
            try:
                from sentence_transformers import SentenceTransformer

                model = SentenceTransformer(self.model_name)
            except Exception as exc:
                logger.exception("Local embedding model failed to load")
                raise AppError(
                    "embedding_model_failure",
                    f"Could not load the local embedding model '{self.model_name}'. "
                    "Install the optional local stack with: "
                    "pip install -r requirements-local.txt",
                    500,
                ) from exc
            self._model = model
            return self._model

    def embed(self, texts, task_type=None):
        model = self._ensure_model()
        try:
            vectors = model.encode(
                list(texts),
                batch_size=self.batch_size,
                convert_to_numpy=True,
                normalize_embeddings=True,
                show_progress_bar=False,
            )
        except Exception as exc:
            logger.exception("Local embedding computation failed")
            raise AppError("embedding_failure", "Failed to compute embeddings locally.", 500) from exc
        return np.asarray(vectors, dtype=np.float32)


