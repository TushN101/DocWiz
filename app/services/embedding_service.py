def validate_embedding_config(config) -> None:
    """Fail fast at startup if the embedding provider settings are unusable.

    Pure checks only — no network calls, no model loads.
    """
    provider = str(config.get("EMBEDDING_PROVIDER", "")).strip().lower()
    if provider not in PROVIDER_DEFAULTS:
        known = ", ".join(sorted(PROVIDER_DEFAULTS))
        raise AppError(
            "embedding_provider_unknown",
            f"EMBEDDING_PROVIDER '{provider}' is not supported. "
            f"Known providers: {known}.",
            500,
        )
    defaults = PROVIDER_DEFAULTS[provider]
    model = config.get("EMBEDDING_MODEL") or defaults["model"]
    if provider == "openai-compatible":
        if not (config.get("EMBEDDING_API_BASE") or "").strip():
            raise AppError(
                "embedding_config_invalid",
                "EMBEDDING_PROVIDER=openai-compatible requires EMBEDDING_API_BASE "
                "(e.g. https://api.jina.ai/v1) and EMBEDDING_MODEL.",
                500,
            )
        if not model:
            raise AppError(
                "embedding_config_invalid",
                "EMBEDDING_PROVIDER=openai-compatible requires EMBEDDING_MODEL.",
                500,
            )
    if provider == "local":
        try:
            import sentence_transformers  # noqa: F401
        except ImportError:
            raise AppError(
                "embedding_config_invalid",
                "EMBEDDING_PROVIDER=local needs the optional local stack: "
                "pip install -r requirements-local.txt (large PyTorch download).",
                500,
            )


