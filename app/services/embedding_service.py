def build_embedding_service(config) -> EmbeddingService:
    """Create the configured EmbeddingService from Flask config values."""
    provider = str(config.get("EMBEDDING_PROVIDER", "gemini")).strip().lower()
    validate_embedding_config(config)
    defaults = PROVIDER_DEFAULTS[provider]

    model = (config.get("EMBEDDING_MODEL") or defaults["model"]).strip()
    api_base = (config.get("EMBEDDING_API_BASE") or defaults["api_base"]).strip()
    output_dims = int(config.get("EMBEDDING_OUTPUT_DIMS") or defaults["output_dims"] or 0)
    batch_size = int(config.get("EMBEDDING_BATCH_SIZE") or 64)
    timeout = float(config.get("EMBEDDING_TIMEOUT_SECONDS") or 30)
    retries = int(config.get("EMBEDDING_MAX_RETRIES") or 2)

    task_document = (config.get("EMBEDDING_TASK_DOCUMENT") or "").strip()
    task_query = (config.get("EMBEDDING_TASK_QUERY") or "").strip()

    if provider == "gemini":
        api_key = (config.get("EMBEDDING_API_KEY") or config.get("GEMINI_API_KEY") or "").strip()
        backend = _GeminiBackend(
            api_key, model, api_base, output_dims, task_document, task_query, timeout, retries
        )
        id_suffix = f":d{output_dims}" if output_dims else ":ddefault"
        embedding_id = f"gemini:{model}{id_suffix}"
        if not api_key:
            logger.warning(
                "No embedding API key configured (EMBEDDING_API_KEY / GEMINI_API_KEY). "
                "Uploads will fail until one is set — %s",
                defaults["key_hint"],
            )
    elif provider == "groq":
        api_key = (config.get("EMBEDDING_API_KEY") or config.get("GROQ_API_KEY") or "").strip()
        backend = _OpenAICompatBackend(api_key, model, api_base, timeout, retries)
        embedding_id = f"groq:{model}:d{output_dims or 'auto'}"
    elif provider == "openai-compatible":
        api_key = (config.get("EMBEDDING_API_KEY") or "").strip()
        backend = _OpenAICompatBackend(api_key, model, api_base, timeout, retries)
        host = re.sub(r"^https?://", "", api_base).split("/")[0]
        embedding_id = f"openai-compatible:{model}@{host}:d{output_dims or 'auto'}"
    elif provider == "hashing":
        dims = int(config.get("EMBEDDING_HASH_DIMS") or defaults["output_dims"])
        backend = _HashingBackend(dims)
        model, embedding_id = f"lexical-hash-{dims}", f"hashing:lexical-hash-{dims}:d{dims}"
    else:  # local
        backend = _LocalSentenceTransformerBackend(model, batch_size)
        embedding_id = f"local:{model}:d{output_dims or 384}"

    cache_enabled = _env_flag(config.get("EMBEDDING_CACHE"), default=True)
    cache_path = None
    data_dir = config.get("DATA_DIR")
    if data_dir:
        cache_path = Path(data_dir) / "embedding_cache.npz"

    service = EmbeddingService(
        provider=provider,
        backend=backend,
        model=model,
        embedding_id=embedding_id,
        cache_path=cache_path,
        cache_enabled=cache_enabled,
    )
    logger.info(
        "Embedding provider: %s (model=%s, id=%s, cache=%s)",
        provider, model, embedding_id, "on" if cache_enabled else "off",
    )
    return service


def _env_flag(value, default=True) -> bool:
    if value is None or value == "":
        return default
    if isinstance(value, bool):
        return value
    return str(value).strip().lower() not in ("0", "false", "no", "off")
